#!/bin/bash
# Regenerate container/shipped-config.sha256: the sha256 of every version of
# each config file the container ships (jobserver.yaml.j2 and the plugin
# YAMLs) found in a release tag, plus the working tree's.  The container's
# start step (mprov_jobserver.container_config) replaces a file in
# /etc/mprov that matches one of these, since the site hasn't edited it
# (#334).  Run from the repository root after changing a shipped default;
# tests/test_container_config.py fails until its hash is listed.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
out=container/shipped-config.sha256
current() {
  echo jobserver.yaml.j2
  for f in src/mprov_jobserver/plugins/*.yaml; do echo "$f"; done
}
{
  echo "# sha256 of every released version of each shipped config file (#334)."
  echo "# Generated by container/gen-shipped-config.sh; don't edit by hand."
  for f in $(current); do
    dest=$f
    [ "$f" = jobserver.yaml.j2 ] || dest=plugins/$(basename "$f")
    {
      for t in $(git tag); do
        git cat-file -e "$t:$f" 2>/dev/null && git show "$t:$f" | sha256sum | cut -d' ' -f1
      done
      sha256sum < "$f" | cut -d' ' -f1
    } | sort -u | sed "s|\$|  $dest|"
  done
} > "$out"
echo "wrote $out ($(grep -vc '^#' "$out") hashes)"
